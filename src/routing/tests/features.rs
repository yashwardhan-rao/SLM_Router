use crate::routing::RoutingConfig;
use crate::routing::complexity::score;
use crate::routing::features::{BUCKETS, Sparse, dense, fnv1a};
use serde::Deserialize;

fn buckets(text: &str) -> Vec<u32> {
    Sparse::of(text).iter().collect()
}

#[test]
fn fnv1a_matches_the_reference_vectors() {
    assert_eq!(fnv1a(&[b""]), 0x811c_9dc5);
    assert_eq!(fnv1a(&[b"a"]), 0xe40c_292c);
    assert_eq!(fnv1a(&[b"foobar"]), 0xbf9c_f968);
    assert_eq!(
        fnv1a(&[b"foo", b"bar"]),
        fnv1a(&[b"foobar"]),
        "parts hash as one string"
    );
}

#[test]
fn empty_and_symbol_only_text_has_no_buckets() {
    assert!(buckets("").is_empty());
    assert!(buckets("  ?! ").is_empty());
    assert_eq!(Sparse::of("").norm(), 0.0);
}

#[test]
fn hyphens_and_case_are_word_separators() {
    assert_eq!(buckets("Lock-Free"), buckets("lock free"));
}

#[test]
fn repeated_text_counts_each_feature_once() {
    assert_eq!(buckets("why why why"), buckets("why why"));
}

#[test]
fn buckets_are_sorted_unique_and_in_range() {
    let b = buckets("Prove that the halting problem is undecidable, step by step.");
    assert!(b.windows(2).all(|w| w[0] < w[1]));
    assert!(b.iter().all(|&x| (x as usize) < BUCKETS));
}

#[test]
fn norm_is_sqrt_of_active_count() {
    let s = Sparse::of("why does it crash");
    assert_eq!(s.norm(), (s.iter().count() as f32).sqrt());
}

#[test]
fn dense_features_are_bounded_and_never_nan() {
    assert_eq!(dense("", 0, 0), [0.0; 4]);
    let d = dense("`x` is O(n)", 1_000_000, 9);
    assert_eq!(d, [1.0, 1.0, 1.0, 1.0], "tokens and cue score clamp to 1");
    assert_eq!(dense("hi", 64, 2)[2..], [0.5, 0.5]);
}

#[derive(Deserialize)]
struct Case {
    text: String,
    est_tokens: usize,
    cue_score: u32,
    buckets: Vec<u32>,
    dense: [f32; 4],
}

/// Generated by `python scripts/features.py --parity`; the trainer uses the same Python code.
#[test]
fn matches_the_python_featurizer() {
    let cases: Vec<Case> = serde_json::from_str(include_str!(
        "../../../tests/fixtures/featurizer_parity.json"
    ))
    .unwrap();
    assert!(cases.len() >= 20);
    for c in &cases {
        let t = &c.text;
        assert_eq!(
            crate::tokens::estimate(t),
            c.est_tokens,
            "est_tokens: {t:?}"
        );
        assert_eq!(
            score(t, &RoutingConfig::default()),
            c.cue_score,
            "cue: {t:?}"
        );
        assert_eq!(buckets(t), c.buckets, "buckets: {t:?}");
        let d = dense(t, c.est_tokens, c.cue_score);
        for (a, b) in d.iter().zip(c.dense) {
            assert!((a - b).abs() < 1e-6, "dense {d:?} vs {:?}: {t:?}", c.dense);
        }
    }
}
